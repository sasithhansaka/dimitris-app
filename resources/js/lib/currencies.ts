const symbolCache = new Map<string, string>();

/**
 * Resolve the display symbol for an ISO 4217 currency code (e.g. "USD" -> "$"),
 * falling back to the code itself if the runtime can't resolve a symbol.
 */
export function currencySymbol(code: string): string {
    if (symbolCache.has(code)) {
        return symbolCache.get(code) as string;
    }

    let symbol = code;

    try {
        const parts = new Intl.NumberFormat('en', {
            style: 'currency',
            currency: code,
            currencyDisplay: 'narrowSymbol',
        }).formatToParts(0);
        symbol = parts.find((part) => part.type === 'currency')?.value ?? code;
    } catch {
        symbol = code;
    }

    symbolCache.set(code, symbol);

    return symbol;
}

export function currencyLabel(code: string): string {
    const symbol = currencySymbol(code);

    return symbol === code ? code : `${code} (${symbol})`;
}

